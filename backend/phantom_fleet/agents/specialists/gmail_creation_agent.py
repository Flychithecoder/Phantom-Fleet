"""
GmailCreationAgent — creates Gmail accounts via Android ADB native account flow.

Strategy: instead of browser automation (heavily fingerprinted), we open
Android Settings > Add Account > Google on a real device via ADB. This is
identical to a user manually adding a Gmail on a new phone — the detection
surface is minimal.

Flow:
    1. Launch Android Settings ADD_ACCOUNT_SETTINGS intent via ADB.
    2. Select Google from account type list (accessibility tap).
    3. Tap "Create account" → "For myself".
    4. Fill first name, last name, birthdate, username, password.
    5. Phone verification via SMS-Activate API.
    6. Skip backup options, accept Terms of Service.
    7. Return the created GmailCredential.

Fleet-scale detection hardening (CLAUDE.md 20K-account rule):
    - All timings are LogNormal — no uniform sleeps anywhere.
    - Typing delays use LogNormal(ln(80ms), 0.3) matching real keystroke CDFs.
    - Tap positions use LogNormal jitter (±3px) around the nominal target.
    - Birth dates use a realistic US birth-month distribution (Jun–Sep peak),
      NOT uniform distribution, because uniform birth-month distributions are
      an ML-detectable cohort fingerprint at scale.
    - Usernames are generated by hash(seed) over a combinatorial pool so
      20K accounts produce 20K different usernames rather than clustering
      around a small template set.
    - Password length follows LogNormal(ln(14), 0.15) — real password lengths
      are not uniformly distributed.

Safety limits (code-enforced, NOT prompt-enforced):
    MAX_ACCOUNTS_PER_PHONE_PER_DAY = 2
    MIN_DELAY_BETWEEN_CREATIONS = 3600 seconds
    MAX_CONCURRENT_CREATIONS = 3
"""
