# ---------------------------------------------------------------------------
# LogNormal / distribution helpers (local, no core import needed)
# ---------------------------------------------------------------------------


def _sha256_seed(*parts: str) -> int:
    """Derive a deterministic int seed from an arbitrary number of string parts."""
    payload = "|".join(parts).encode("utf-8")
    digest = hashlib.sha256(payload).digest()
    return int.from_bytes(digest[:8], "big", signed=False)


def _seeded_random(seed: int, offset: int = 0) -> float:
    """Return a deterministic float in [0, 1) from seed + offset.

    Uses SHA-256 so sequential seeds don't produce correlated values.
    """
    payload = f"{seed}:{offset}".encode("utf-8")
    digest = hashlib.sha256(payload).digest()
    val = int.from_bytes(digest[:4], "big", signed=False)
    return val / 0xFFFFFFFF


def _lognormal(mu_ln: float, sigma_ln: float, seed: int, offset: int = 0) -> float:
    """Sample from LogNormal(mu_ln, sigma_ln) using Box-Muller + seeded random.

    mu_ln and sigma_ln are the mean and std of the *underlying normal*.
    Returns the exponentiated value (i.e. the actual LogNormal sample).
    """
    u1 = _seeded_random(seed, offset)
    u2 = _seeded_random(seed, offset + 1)
    # Box-Muller transform
    u1 = max(u1, 1e-9)  # guard against log(0)
    z = math.sqrt(-2.0 * math.log(u1)) * math.cos(2.0 * math.pi * u2)
    return math.exp(mu_ln + sigma_ln * z)


def _weighted_choice(weights: list[float], seed: int, offset: int = 0) -> int:
    """Return an index sampled from the given weight distribution."""
    r = _seeded_random(seed, offset)
    cumulative = 0.0
    for i, w in enumerate(weights):
        cumulative += w
        if r <= cumulative:
            return i
    return len(weights) - 1  # fallback for floating point edge


