    def _check_phone_rate_limit(self, serial: str) -> Optional[str]:
        """Enforce MAX_ACCOUNTS_PER_PHONE_PER_DAY and MIN_DELAY_BETWEEN_CREATIONS.

        Returns:
            None if the phone is clear to create another account.
            An error string if a limit is hit.
        """
        import time

        now = time.time()
        log_for_phone = self._phone_creation_log.get(serial, [])

        # Prune entries older than 24 hours
        log_for_phone = [t for t in log_for_phone if now - t < 86400]
        self._phone_creation_log[serial] = log_for_phone

        if len(log_for_phone) >= MAX_ACCOUNTS_PER_PHONE_PER_DAY:
            return (
                f"Phone {serial} has already created "
                f"{MAX_ACCOUNTS_PER_PHONE_PER_DAY} accounts in the last 24h"
            )

        if log_for_phone:
            last_creation = max(log_for_phone)
            elapsed = now - last_creation
            if elapsed < MIN_DELAY_BETWEEN_CREATIONS:
                remaining = int(MIN_DELAY_BETWEEN_CREATIONS - elapsed)
                return (
                    f"Phone {serial} must wait {remaining}s more before next creation "
                    f"(min gap: {MIN_DELAY_BETWEEN_CREATIONS}s)"
                )

        return None

    def _record_creation(self, serial: str) -> None:
        """Record a successful creation timestamp for the given phone serial."""
        import time

        if serial not in self._phone_creation_log:
            self._phone_creation_log[serial] = []
        self._phone_creation_log[serial].append(time.time())
