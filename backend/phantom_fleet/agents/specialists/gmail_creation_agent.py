class GmailCreationAgent:
    """Creates Gmail accounts via Android ADB native account settings flow.

    Each call to ``create_account`` occupies one slot in the module-level
    semaphore (MAX_CONCURRENT_CREATIONS = 3) so the fleet never exceeds 3
    simultaneous creations regardless of how many callers invoke the agent.

    Per-phone rate limiting is enforced via ``_phone_creation_log`` which
    records timestamps of past creations per serial. The agent refuses to
    create more than MAX_ACCOUNTS_PER_PHONE_PER_DAY accounts on a single
    phone within a 24-hour window, and enforces a minimum of
    MIN_DELAY_BETWEEN_CREATIONS seconds between consecutive creations on the
    same phone.
    """

    def __init__(self, sms_activate_api_key: str) -> None:
        self._sms_key = sms_activate_api_key
        # serial → list of creation timestamps (epoch seconds)
        self._phone_creation_log: dict[str, list[float]] = {}
        # Set of used usernames (process-local; persist externally via GmailAccountPool)
        self._used_usernames: set[str] = set()

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    async def create_account(
        self, phone_serial: str
    ) -> CreationResult:
        """Create one Gmail account on the given ADB-connected Android device.

        Enforces all safety limits before starting. Returns CreationResult
        with success=False and an error string if any guard fires.

        Args:
            phone_serial: ADB device serial (e.g. "emulator-5554" or
                          "R5CT1012XYZ").

        Returns:
            CreationResult with a populated GmailCredential on success.
        """
        start = asyncio.get_event_loop().time()

        # --- Code-enforced safety gates ---
        guard_error = self._check_phone_rate_limit(phone_serial)
        if guard_error:
            return CreationResult(
                success=False,
                error=guard_error,
                duration_seconds=asyncio.get_event_loop().time() - start,
            )

        async with _creation_semaphore:
            try:
                cred = await self._run_creation_flow(phone_serial)
                self._record_creation(phone_serial)
                return CreationResult(
                    success=True,
                    credential=cred,
                    duration_seconds=asyncio.get_event_loop().time() - start,
                )
            except Exception as exc:  # noqa: BLE001
                log.exception("Gmail creation failed on %s: %s", phone_serial, exc)
                return CreationResult(
                    success=False,
                    error=str(exc),
                    duration_seconds=asyncio.get_event_loop().time() - start,
                )

    # ------------------------------------------------------------------
    # Internal creation flow
    # ------------------------------------------------------------------

    async def _run_creation_flow(self, serial: str) -> GmailCredential:
        """Execute the full ADB-native Gmail creation flow."""
        seed = _sha256_seed(serial, str(secrets.randbelow(2**32)))

        first = _FIRST_NAMES[seed % len(_FIRST_NAMES)]
        last = _LAST_NAMES[(seed >> 8) % len(_LAST_NAMES)]
        bday = self._generate_birth_date(seed)
        username = self._generate_username(first, last, seed)
        password = self._generate_password(seed)

        log.info("[%s] Starting Gmail creation: %s %s → %s", serial, first, last, username)

        # 1. Launch account settings
        await self._adb(serial, "shell", "am", "start",
                        "-a", "android.settings.ADD_ACCOUNT_SETTINGS")
        await self._lognormal_sleep(2.5, 0.25, seed, 0)

        # 2. Select Google from the account type list
        await self._wait_for_activity(serial, "ChooseTypeOfAccountActivity")
        # "Google" item is typically around y=700 on a standard FHD device
        await self._tap(serial, 540, 700, seed, 1)
        await self._lognormal_sleep(2.0, 0.3, seed, 2)

        # 3. Tap "Create account"
        await self._tap(serial, 540, 900, seed, 3)
        await self._lognormal_sleep(1.5, 0.3, seed, 4)

        # 4. "For myself"
        await self._tap(serial, 540, 650, seed, 5)
        await self._lognormal_sleep(1.8, 0.25, seed, 6)

        # 5. Enter first name
        await self._tap(serial, 300, 500, seed, 7)
        await self._type_text(serial, first, seed, base_offset=10)
        await self._tap(serial, 700, 500, seed, 8)  # last name field
        await self._type_text(serial, last, seed, base_offset=20)
        await self._tap(serial, 950, 1700, seed, 9)  # "Next" button
        await self._lognormal_sleep(1.5, 0.3, seed, 10)

        # 6. Birth date + gender
        # Month
        await self._tap(serial, 150, 600, seed, 11)
        await self._adb(serial, "shell", "input", "text", str(bday[1]))
        await self._lognormal_sleep(0.4, 0.2, seed, 12)
        # Day
        await self._tap(serial, 380, 600, seed, 13)
        await self._adb(serial, "shell", "input", "text", str(bday[2]))
        await self._lognormal_sleep(0.4, 0.2, seed, 14)
        # Year
        await self._tap(serial, 610, 600, seed, 15)
        await self._adb(serial, "shell", "input", "text", str(bday[0]))
        await self._lognormal_sleep(0.5, 0.2, seed, 16)
        # Gender dropdown — pick "Female" (index 1 in spinner)
        await self._tap(serial, 540, 750, seed, 17)
        await self._lognormal_sleep(0.8, 0.2, seed, 18)
        await self._tap(serial, 540, 720, seed, 19)  # "Female" in dropdown
        await self._lognormal_sleep(0.5, 0.2, seed, 20)
        await self._tap(serial, 950, 1700, seed, 21)  # Next
        await self._lognormal_sleep(1.5, 0.3, seed, 22)

        # 7. Username — try generated username, fall back on suffix variants
        await self._tap(serial, 540, 600, seed, 23)
        await self._type_text(serial, username, seed, base_offset=30)
        await self._tap(serial, 950, 1700, seed, 24)  # Next
        await self._lognormal_sleep(2.0, 0.3, seed, 25)

        # 8. Password
        await self._tap(serial, 540, 600, seed, 26)
        await self._type_text(serial, password, seed, base_offset=50)
        await self._tap(serial, 540, 750, seed, 27)  # Confirm password field
        await self._type_text(serial, password, seed, base_offset=70)
        await self._tap(serial, 950, 1700, seed, 28)  # Next
        await self._lognormal_sleep(2.0, 0.3, seed, 29)

        # 9. Phone verification
        phone_number = await self._get_sms_number(seed)
        await self._tap(serial, 540, 600, seed, 30)
        await self._type_text(serial, phone_number.lstrip("+"), seed, base_offset=90)
        await self._tap(serial, 950, 1700, seed, 31)  # Send verification
        await self._lognormal_sleep(3.5, 0.3, seed, 32)

        sms_code = await self._wait_for_sms_code(phone_number, seed)
        await self._tap(serial, 540, 600, seed, 33)
        await self._type_text(serial, sms_code, seed, base_offset=110)
        await self._tap(serial, 950, 1700, seed, 34)  # Verify
        await self._lognormal_sleep(2.5, 0.3, seed, 35)

        # 10. Skip recovery email / backup options
        await self._tap(serial, 540, 1000, seed, 36)  # "Skip" button
        await self._lognormal_sleep(1.5, 0.25, seed, 37)

        # 11. Accept Terms of Service
        await self._tap(serial, 950, 1700, seed, 38)  # "I agree"
        await self._lognormal_sleep(3.0, 0.3, seed, 39)

        email = f"{username}@gmail.com"
        log.info("[%s] Gmail creation complete: %s", serial, email)

        return GmailCredential(
            email=email,
            password=password,
            first_name=first,
            last_name=last,
            phone_number_used=phone_number,
            created_at_iso=datetime.now(timezone.utc).isoformat(),
            phone_serial=serial,
            account_seed=seed,
        )

    # ------------------------------------------------------------------
    # Username / password / birthdate generation
    # ------------------------------------------------------------------

    def _generate_username(self, first: str, last: str, seed: int) -> str:
        """Generate a Gmail username that isn't already in the used set.

        Tries patterns in order:
            1. {first}{last}
            2. {first}.{last}{2-digit suffix}
            3. {first}{last}{3-digit suffix}
        Falls back to adding increasing numeric suffixes until unique.

        Args:
            first: First name (lowercase applied internally).
            last: Last name (lowercase applied internally).
            seed: Deterministic seed for suffix selection.

        Returns:
            A username string not present in self._used_usernames.
        """
        f = first.lower()
        la = last.lower()

        candidates: list[str] = [f"{f}{la}"]
        for i in range(100):
            suffix_2 = str((seed + i * 7) % 100).zfill(2)
            candidates.append(f"{f}.{la}{suffix_2}")
        for i in range(100):
            suffix_3 = str((seed + i * 13) % 1000).zfill(3)
            candidates.append(f"{f}{la}{suffix_3}")

        for candidate in candidates:
            if candidate not in self._used_usernames:
                self._used_usernames.add(candidate)
                return candidate

        # Last resort: append a random 6-digit suffix using secrets
        fallback = f"{f}{la}{secrets.randbelow(900000) + 100000}"
        self._used_usernames.add(fallback)
        return fallback

    def _generate_password(self, seed: int) -> str:
        """Generate a password with LogNormal-distributed length.

        Length ~ LogNormal(ln(14), 0.15) so the fleet-wide length histogram
        matches a realistic bell-curve centered at ~14 chars (range 12–18).

        Composition: uppercase, lowercase, digits, symbols (!"#$%&). Never
        all-alpha or all-digit — must pass Google's strength validator.

        Args:
            seed: Deterministic seed.

        Returns:
            A password string 12–18 characters long.
        """
        raw_len = _lognormal(math.log(14), 0.15, seed, 200)
        length = max(12, min(18, round(raw_len)))

        chars_upper = string.ascii_uppercase
        chars_lower = string.ascii_lowercase
        chars_digits = string.digits
        chars_symbols = "!@#$%&*"

        # Guarantee at least one of each character class
        parts: list[str] = [
            chars_upper[_sha256_seed(str(seed), "u") % len(chars_upper)],
            chars_lower[_sha256_seed(str(seed), "l") % len(chars_lower)],
            chars_digits[_sha256_seed(str(seed), "d") % len(chars_digits)],
            chars_symbols[_sha256_seed(str(seed), "s") % len(chars_symbols)],
        ]

        all_chars = chars_upper + chars_lower + chars_digits + chars_symbols
        for i in range(length - 4):
            parts.append(all_chars[_sha256_seed(str(seed), f"f{i}") % len(all_chars)])

        # Shuffle using seeded Fisher-Yates
        rng_seed = _sha256_seed(str(seed), "shuffle")
        for i in range(len(parts) - 1, 0, -1):
            j = _sha256_seed(str(rng_seed), str(i)) % (i + 1)
            parts[i], parts[j] = parts[j], parts[i]

        return "".join(parts)

    def _generate_birth_date(self, account_seed: int) -> tuple[int, int, int]:
        """Generate a birth date for a 22–30 year old (1994–2002 birth years).

        Birth month is sampled from a realistic US seasonal distribution
        (_BIRTH_MONTH_WEIGHTS) — NOT uniform, since uniform birth-month
        distributions are a detectable cohort fingerprint at fleet scale.
        Birth day is sampled uniformly within the chosen month.
        Birth year is sampled uniformly within [1994, 2002].

        Args:
            account_seed: Deterministic seed.

        Returns:
            Tuple of (year, month, day) where month is 1-indexed.
        """
        # Year: uniform 1994–2002 (9 values) — year of birth is not
        # population-observable from the account so uniform is fine here.
        year_offset = _sha256_seed(str(account_seed), "bday_year") % 9
        year = 1994 + year_offset

        # Month: weighted by realistic US birth distribution
        month_idx = _weighted_choice(
            _BIRTH_MONTH_WEIGHTS,
            _sha256_seed(str(account_seed), "bday_month"),
        )
        month = month_idx + 1  # 1-indexed

        # Day: uniform within the month
        days_in_m = _DAYS_IN_MONTH[month_idx]
        day_seed = _sha256_seed(str(account_seed), "bday_day")
        day = (day_seed % days_in_m) + 1

        return (year, month, day)

    # ------------------------------------------------------------------
    # SMS-Activate integration
    # ------------------------------------------------------------------

    async def _get_sms_number(self, seed: int) -> str:
        """Request a US phone number from SMS-Activate for Google verification.

        Returns:
            Phone number string in E.164 format, e.g. "+12025551234".

        Raises:
            RuntimeError: If SMS-Activate does not return a number within
                          the retry window.
        """
        url = "https://api.sms-activate.org/stubs/handler_api.php"
        params = {
            "api_key": self._sms_key,
            "action": "getNumber",
            "service": "go",  # Google
            "country": "0",  # Russia — cheapest. Use 187 for US.
        }
        async with httpx.AsyncClient(timeout=30.0) as client:
            for attempt in range(5):
                resp = await client.get(url, params=params)
                text = resp.text.strip()
                if text.startswith("ACCESS_NUMBER"):
                    # Response: ACCESS_NUMBER:{activation_id}:{phone}
                    parts = text.split(":")
                    phone_raw = parts[2].strip()
                    # Normalise to E.164
                    phone = "+" + phone_raw.lstrip("+")
                    log.info("SMS-Activate number assigned: %s", phone)
                    return phone
                if text == "NO_NUMBERS":
                    log.warning("SMS-Activate: NO_NUMBERS, attempt %d/5", attempt + 1)
                    await asyncio.sleep(_lognormal(math.log(10), 0.3, seed, 300 + attempt))
                else:
                    raise RuntimeError(f"SMS-Activate unexpected response: {text}")
        raise RuntimeError("SMS-Activate: no numbers available after 5 attempts")

    async def _wait_for_sms_code(self, phone_number: str, seed: int) -> str:
        """Poll SMS-Activate for the verification code sent to phone_number.

        Polls up to 20 times with ~15s intervals (LogNormal jitter) before
        giving up.

        Args:
            phone_number: E.164 phone number previously assigned.
            seed: Deterministic seed for timing jitter.

        Returns:
            6-digit SMS verification code string.

        Raises:
            RuntimeError: If code not received within the polling window.
        """
        # We need the activation_id — for simplicity, derive from phone hash.
        # In production, store the activation_id returned by _get_sms_number.
        url = "https://api.sms-activate.org/stubs/handler_api.php"
        activation_id_placeholder = hashlib.sha256(phone_number.encode()).hexdigest()[:8]
        params = {
            "api_key": self._sms_key,
            "action": "getStatus",
            "id": activation_id_placeholder,
        }
        async with httpx.AsyncClient(timeout=30.0) as client:
            for attempt in range(20):
                await asyncio.sleep(_lognormal(math.log(15), 0.25, seed, 400 + attempt))
                resp = await client.get(url, params=params)
                text = resp.text.strip()
                if text.startswith("STATUS_OK"):
                    code = text.split(":")[1]
                    log.info("SMS code received for %s: %s", phone_number, code)
                    return code
                if text in ("STATUS_WAIT_CODE", "STATUS_WAIT_RESEND"):
                    log.debug("Waiting for SMS code (attempt %d/20)", attempt + 1)
                    continue
                if text == "STATUS_CANCEL":
                    raise RuntimeError("SMS-Activate: activation cancelled")
        raise RuntimeError(f"SMS code not received for {phone_number} after 20 polls")

    # ------------------------------------------------------------------
    # ADB interaction helpers
    # ------------------------------------------------------------------

    async def _adb(self, serial: str, *args: str) -> str:
        """Async wrapper for ADB commands. Returns stdout text.

        Args:
            serial: ADB device serial.
            *args: ADB sub-command arguments.

        Returns:
            stdout of the ADB command.

        Raises:
            RuntimeError: If ADB exits with non-zero status.
        """
        cmd = ["adb", "-s", serial, *args]
        proc = await asyncio.create_subprocess_exec(
            *cmd,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        stdout, stderr = await proc.communicate()
        if proc.returncode != 0:
            raise RuntimeError(
                f"ADB error (rc={proc.returncode}): {stderr.decode().strip()}"
            )
        return stdout.decode().strip()

    async def _tap(
        self, serial: str, x: int, y: int, seed: int, offset: int
    ) -> None:
        """Tap screen coordinates with LogNormal jitter (±3px nominal).

        Jitter magnitude uses LogNormal(ln(2), 0.4) clipped to ±5px so the
        distribution has a realistic long tail (sometimes 4–5px off centre)
        rather than the unnatural ±3px hard boundary a uniform distribution
        would produce.

        Args:
            serial: ADB device serial.
            x: Nominal tap X coordinate.
            y: Nominal tap Y coordinate.
            seed: Parent seed.
            offset: Offset to differentiate tap calls.
        """
        jitter_mag = _lognormal(math.log(2), 0.4, seed, offset)
        jitter_x = int(jitter_mag * (1 if _seeded_random(seed, offset + 1000) > 0.5 else -1))
        jitter_y = int(jitter_mag * (1 if _seeded_random(seed, offset + 2000) > 0.5 else -1))
        tx = x + max(-5, min(5, jitter_x))
        ty = y + max(-5, min(5, jitter_y))
        await self._adb(serial, "shell", "input", "tap", str(tx), str(ty))

    async def _type_text(
        self, serial: str, text: str, seed: int, base_offset: int = 0
    ) -> None:
        """Type text character by character with LogNormal inter-key delays.

        Inter-key delay ~ LogNormal(ln(80ms), 0.3) matching real human
        keystroke CDFs from published typing latency studies.

        Special characters are escaped for ADB shell input.

        Args:
            serial: ADB device serial.
            text: String to type.
            seed: Parent seed.
            base_offset: Offset base for delay sampling.
        """
        for i, char in enumerate(text):
            # Escape special shell characters for adb shell input text
            if char in " \"'\\&|;<>(){}[]$`!#":
                escaped = "\\" + char
            else:
                escaped = char
            await self._adb(serial, "shell", "input", "text", escaped)
            delay = _lognormal(math.log(0.08), 0.3, seed, base_offset + i)
            delay = max(0.03, min(0.3, delay))  # clip to [30ms, 300ms]
            await asyncio.sleep(delay)

    async def _wait_for_activity(
        self, serial: str, activity_name: str, timeout: int = 15
    ) -> None:
        """Poll dumpsys activity until the named activity is the focused window.

        Args:
            serial: ADB device serial.
            activity_name: Partial activity class name to wait for.
            timeout: Maximum seconds to wait before raising TimeoutError.

        Raises:
            TimeoutError: If the activity does not appear within timeout.
        """
        deadline = asyncio.get_event_loop().time() + timeout
        while asyncio.get_event_loop().time() < deadline:
            try:
                output = await self._adb(
                    serial, "shell", "dumpsys", "activity", "activities"
                )
                if activity_name in output:
                    return
            except RuntimeError:
                pass
            await asyncio.sleep(0.5)
        raise TimeoutError(
            f"Activity '{activity_name}' not visible on {serial} after {timeout}s"
        )

    async def _lognormal_sleep(
        self, mu_ln: float, sigma_ln: float, seed: int, offset: int
    ) -> None:
        """Sleep for a LogNormal-distributed duration.

        Args:
            mu_ln: Mean of the underlying normal (i.e. ln of target median).
            sigma_ln: Std of the underlying normal.
            seed: Deterministic seed.
            offset: Call-site offset for independence.
        """
        duration = _lognormal(mu_ln, sigma_ln, seed, offset)
        duration = max(0.3, duration)  # floor at 300ms
        await asyncio.sleep(duration)

