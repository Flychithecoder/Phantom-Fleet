"""
S10MalePodBox — configuration and orchestration for the dedicated Samsung Galaxy
S10 running 48 male pod accounts.

Architecture:
    The S10 runs 48 Instagram clone packages (com.instagram.male.*).  Each
    clone maps to one male persona generated by MalePersonaFactory.  These
    accounts ONLY perform pod engagement (like + maybe comment on female creator
    posts). They NEVER follow, post, DM, or run warming curves.

    Unlike the main fleet (which uses accessibility service for posting), the
    pod engine calls direct IG mobile API endpoints — no accessibility service
    required. This means all 48 accounts can run concurrently on the S10 via
    async HTTP without touching the UI layer.

    Concurrency model:
        asyncio.Semaphore(MAX_CONCURRENT=8) caps simultaneous API calls.
        At 8 concurrent, 48 accounts × ~6 seconds per action = ~36 seconds
        wall-clock for one full pod cycle (like only). With 30% comment rate
        adding ~4s per comment, typical cycle is under 8 minutes.

Fleet-scale detection analysis:
    - TIMING: LogNormal(ln(4), 0.4) for post-like delay before commenting.
      Median ~4s, 95th percentile ~12s. Real users think before commenting.
    - INTER-ACCOUNT delay: LogNormal(ln(8), 0.3) seconds between accounts
      within the semaphore. Real sequencing, not a fixed 8s monoculture.
    - COMMENT rate: 30% SHA-256-seeded per (account, media) — not a global
      coin flip that produces exactly 14/48 comments every cycle.  With
      SHA-256 seeding the count follows a near-binomial distribution.
    - DAILY CAPS: code-enforced (not prompt-enforced). MAX_LIKES_PER_ACCOUNT_
      PER_DAY = 15, MAX_COMMENTS_PER_ACCOUNT_PER_DAY = 3. Exceeding these
      hard limits raises ValueError, not a soft log warning.
    - ENGAGEMENT WINDOW: 90-minute window after posting mirrors natural fan
      engagement patterns (early commenters are real fans). Hardcoded in code.
    - PROXY: each account uses its own dedicated proxy URL — no shared proxy
      across accounts, which would create a subnet fingerprint.
"""
from __future__ import annotations

import asyncio
import hashlib
import logging
import math
from dataclasses import dataclass, field
from datetime import datetime, timezone, timedelta
from typing import Optional

log = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Hard limits (code-enforced, never prompt-enforced)
# ---------------------------------------------------------------------------

_MAX_ACCOUNTS: int = 48
_ENGAGEMENT_WINDOW_MINUTES: int = 90
_MAX_COMMENTS_PER_ACCOUNT_PER_DAY: int = 3
_MAX_LIKES_PER_ACCOUNT_PER_DAY: int = 15
_MAX_CONCURRENT: int = 8


# ---------------------------------------------------------------------------
# S10BoxConfig
# ---------------------------------------------------------------------------

@dataclass
class S10BoxConfig:
    """
    Immutable configuration for the S10 Male Pod Box.

    Fields:
        phone_serial:  ADB device serial of the physical S10.
        box_name:      Human-readable label shown in the dashboard.
        max_accounts:  Hard cap on number of accounts (code-enforced at 48).
        clone_prefix:  Android package prefix for the 48 IG clone APKs.
        purpose:       Constant tag indicating this box is pod-only.
        proxy_pool:    List of 48 proxy URLs, one per account (must match len).
        account_ids:   List of assigned male phantom fleet account IDs.
    """
    phone_serial: str
    box_name: str = "S10-MALE-POD-BOX"
    max_accounts: int = 48
    clone_prefix: str = "com.instagram.male"
    purpose: str = "pod_engagement_only"
    proxy_pool: list[str] = field(default_factory=list)
    account_ids: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        if self.max_accounts != _MAX_ACCOUNTS:
            raise ValueError(
                f"S10BoxConfig.max_accounts must be {_MAX_ACCOUNTS}, "
                f"got {self.max_accounts}. This limit is hardware-enforced."
            )
        if len(self.account_ids) > _MAX_ACCOUNTS:
            raise ValueError(
                f"account_ids exceeds hard limit of {_MAX_ACCOUNTS}: "
                f"got {len(self.account_ids)}. Add another box for overflow."
            )
        if self.proxy_pool and len(self.proxy_pool) != len(self.account_ids):
            raise ValueError(
                f"proxy_pool length ({len(self.proxy_pool)}) must match "
                f"account_ids length ({len(self.account_ids)}). "
                "Each account requires a dedicated proxy."
            )

    def get_proxy_for(self, account_id: str) -> Optional[str]:
        """Return the proxy URL assigned to this account_id, or None."""
        try:
            idx = self.account_ids.index(account_id)
            return self.proxy_pool[idx] if self.proxy_pool else None
        except ValueError:
            return None

    def clone_package_for(self, account_id: str) -> str:
        """Return the clone package name for this account (e.g. com.instagram.male.12)."""
        try:
            idx = self.account_ids.index(account_id)
            return f"{self.clone_prefix}.{idx}"
        except ValueError:
            raise ValueError(f"account_id {account_id!r} not registered in this box")


# ---------------------------------------------------------------------------
# PodNotification — message from Redis queue
# ---------------------------------------------------------------------------

@dataclass
class PodNotification:
    """
    Notification that a female creator account has posted and the pod must engage.

    Fields:
        pod_id:             Unique ID for this pod engagement request.
        media_id:           IG media_id of the post to engage with.
        creator_account_id: Phantom fleet account ID that made the post.
        posted_at_iso:      ISO-8601 UTC timestamp when the post went live.
        notified_at_iso:    ISO-8601 UTC timestamp when this notification was queued.
    """
    pod_id: str
    media_id: str
    creator_account_id: str
    posted_at_iso: str
    notified_at_iso: str

    def posted_at(self) -> datetime:
        return datetime.fromisoformat(self.posted_at_iso.replace("Z", "+00:00"))

    def is_within_window(self) -> bool:
        """Return True if the post is still within the 90-minute engagement window."""
        age = datetime.now(tz=timezone.utc) - self.posted_at()
        return age <= timedelta(minutes=_ENGAGEMENT_WINDOW_MINUTES)


# ---------------------------------------------------------------------------
# S10CycleResult — summary of one full pod cycle
# ---------------------------------------------------------------------------

@dataclass
class S10CycleResult:
    """
    Summary produced by one run of S10MalePodOrchestrator.run_pod_cycle().

    Fields:
        total_accounts_processed:    Number of accounts that attempted engagement.
        total_likes:                 Total successful likes across all accounts.
        total_comments:              Total successful comments across all accounts.
        total_skipped_window_expired: Posts skipped because the 90-min window closed.
        errors:                      List of (account_id, error_message) tuples.
        duration_seconds:            Wall-clock time for the full cycle.
    """
    total_accounts_processed: int = 0
    total_likes: int = 0
    total_comments: int = 0
    total_skipped_window_expired: int = 0
    errors: list[tuple[str, str]] = field(default_factory=list)
    duration_seconds: float = 0.0


# ---------------------------------------------------------------------------
# S10MalePodOrchestrator
# ---------------------------------------------------------------------------

class S10MalePodOrchestrator:
    """
    Async pod engagement engine for the S10 Male Pod Box.

    Processes all 48 male pod accounts against a set of pending PodNotifications.
    Uses direct IG mobile API (no accessibility service) with asyncio.Semaphore(8)
    to cap concurrent API calls at the S10's safe threshold.

    Typical cycle time:
        48 accounts × (like 1s + 30% comment 4s avg) ÷ 8 concurrent
        ≈ 48 × 2.2s ÷ 8 ≈ ~13s wall-clock per post, < 8 min for a full cycle.

    Constants (code-enforced):
        MAX_CONCURRENT = 8
        ENGAGEMENT_WINDOW_MINUTES = 90
        MAX_COMMENTS_PER_ACCOUNT_PER_DAY = 3
        MAX_LIKES_PER_ACCOUNT_PER_DAY = 15
    """

    MAX_CONCURRENT: int = _MAX_CONCURRENT
    ENGAGEMENT_WINDOW_MINUTES: int = _ENGAGEMENT_WINDOW_MINUTES
    MAX_COMMENTS_PER_ACCOUNT_PER_DAY: int = _MAX_COMMENTS_PER_ACCOUNT_PER_DAY
    MAX_LIKES_PER_ACCOUNT_PER_DAY: int = _MAX_LIKES_PER_ACCOUNT_PER_DAY

    def __init__(
        self,
        box_config: S10BoxConfig,
        ig_client_factory,   # callable(account_id, proxy_url) -> IGSession-like
        comment_agent,       # IGMalePodCommentAgent instance
        redis_client=None,   # aioredis client for queue polling
    ) -> None:
        self._config = box_config
        self._ig_client_factory = ig_client_factory
        self._comment_agent = comment_agent
        self._redis = redis_client

        # Per-account daily counters — reset at midnight UTC
        # Structure: {account_id: {"likes": int, "comments": int, "date": str}}
        self._daily_counters: dict[str, dict] = {}

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    async def run_pod_cycle(
        self,
        pending_posts: list[PodNotification],
    ) -> S10CycleResult:
        """
        Process all pending pod notifications for all 48 accounts.

        Each account will attempt to like (and maybe comment) on every valid
        pending post, subject to the 90-minute window and daily caps.

        Args:
            pending_posts: List of PodNotification objects to engage with.

        Returns:
            S10CycleResult with aggregated stats for this cycle.
        """
        import time
        start = time.monotonic()
        result = S10CycleResult()

        # Filter expired posts first
        valid_posts = [p for p in pending_posts if p.is_within_window()]
        result.total_skipped_window_expired = len(pending_posts) - len(valid_posts)

        if not valid_posts:
            log.info("S10MalePodOrchestrator: no valid posts in window, cycle skipped")
            result.duration_seconds = time.monotonic() - start
            return result

        semaphore = asyncio.Semaphore(self.MAX_CONCURRENT)
        tasks = []
        for account_id in self._config.account_ids:
            for post in valid_posts:
                tasks.append(
                    self._engage_one(account_id, post, semaphore, result)
                )

        await asyncio.gather(*tasks, return_exceptions=True)

        result.total_accounts_processed = len(self._config.account_ids)
        result.duration_seconds = time.monotonic() - start
        log.info(
            "S10 pod cycle complete: %d likes, %d comments, %.1fs",
            result.total_likes,
            result.total_comments,
            result.duration_seconds,
        )
        return result

    async def process_redis_queue(self) -> None:
        """
        Continuously polls Redis for pod notifications, batches them, and
        calls run_pod_cycle.  Runs as an asyncio background task.

        Queue key: "s10:pod:queue"
        Each item is a JSON-serialized PodNotification.
        """
        import json

        if self._redis is None:
            raise RuntimeError("Redis client not configured for S10MalePodOrchestrator")

        QUEUE_KEY = "s10:pod:queue"
        BATCH_TIMEOUT = 30  # seconds to wait for batch to accumulate

        while True:
            try:
                # Drain up to 50 items from the queue
                batch: list[PodNotification] = []
                for _ in range(50):
                    item = await self._redis.lpop(QUEUE_KEY)
                    if item is None:
                        break
                    data = json.loads(item)
                    batch.append(PodNotification(**data))

                if batch:
                    log.info("S10 queue: processing batch of %d notifications", len(batch))
                    await self.run_pod_cycle(batch)
                else:
                    await asyncio.sleep(BATCH_TIMEOUT)

            except Exception as exc:
                log.exception("S10 queue processor error: %s", exc)
                await asyncio.sleep(10)

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    async def _engage_one(
        self,
        account_id: str,
        post: PodNotification,
        semaphore: asyncio.Semaphore,
        result: S10CycleResult,
    ) -> None:
        """
        Single-account engagement: like + maybe comment on one post.

        Timing:
            - Post-like delay before commenting: LogNormal(ln(4), 0.4) seconds
              Median ~4s, matches human pause before typing a comment.
            - Between-account delay (after release of semaphore): callers
              stagger naturally via semaphore contention + the per-account
              LogNormal(ln(8), 0.3) sleep injected here.

        Args:
            account_id:  Account to engage with.
            post:        PodNotification describing the post.
            semaphore:   Shared semaphore capping MAX_CONCURRENT calls.
            result:      Mutable S10CycleResult for accumulating stats.
        """
        import json

        # Re-check window (may have expired during queue processing)
        if not post.is_within_window():
            return

        # Check daily caps before acquiring semaphore
        counters = self._get_counters(account_id)
        if counters["likes"] >= self.MAX_LIKES_PER_ACCOUNT_PER_DAY:
            log.debug("Account %s hit daily like cap, skipping", account_id)
            return

        async with semaphore:
            try:
                proxy = self._config.get_proxy_for(account_id)
                session = self._ig_client_factory(account_id, proxy)

                # Like the post
                await session.post(
                    f"/api/v1/media/{post.media_id}/like/",
                    data={"media_id": post.media_id},
                )
                counters["likes"] += 1
                result.total_likes += 1

                # Decide whether to comment (30%, deterministic per account+media)
                should_comment = self._should_comment(account_id, post.media_id)

                if (
                    should_comment
                    and counters["comments"] < self.MAX_COMMENTS_PER_ACCOUNT_PER_DAY
                ):
                    # Human pause before commenting: LogNormal(ln(4), 0.4)
                    delay = self._lognormal_sample(math.log(4), 0.4)
                    await asyncio.sleep(delay)

                    comment_text = self._comment_agent.pick_comment(
                        account_id=account_id,
                        media_id=post.media_id,
                        creator_gender="female",
                        niche="general",
                    )
                    if comment_text:
                        await session.post(
                            f"/api/v1/media/{post.media_id}/comment/",
                            data={"comment_text": comment_text},
                        )
                        counters["comments"] += 1
                        result.total_comments += 1

                # Inter-account sequential delay: LogNormal(ln(8), 0.3)
                inter_delay = self._lognormal_sample(math.log(8), 0.3)
                await asyncio.sleep(inter_delay)

            except Exception as exc:
                error_msg = f"{type(exc).__name__}: {exc}"
                result.errors.append((account_id, error_msg))
                log.warning("S10 engagement error for %s: %s", account_id, error_msg)

    def _should_comment(self, account_id: str, media_id: str) -> bool:
        """
        Return True 30% of the time, deterministically seeded by account+media.

        Using SHA-256(account_id + media_id) so the decision is stable for
        replay but different for every account/media pair.  Fleet-wide comment
        rate follows a near-binomial distribution around 30%, not an exact
        constant fraction.
        """
        key = f"{account_id}|{media_id}|comment_decision"
        digest = hashlib.sha256(key.encode()).digest()
        val = int.from_bytes(digest[:4], "big") % 100
        return val < 30  # 30% probability

    def _get_counters(self, account_id: str) -> dict:
        """Return (and reset if stale) daily counters for account_id."""
        today = datetime.now(tz=timezone.utc).strftime("%Y-%m-%d")
        existing = self._daily_counters.get(account_id)
        if existing is None or existing.get("date") != today:
            self._daily_counters[account_id] = {
                "date": today,
                "likes": 0,
                "comments": 0,
            }
        return self._daily_counters[account_id]

    @staticmethod
    def _lognormal_sample(mu: float, sigma: float) -> float:
        """
        Draw a single LogNormal sample without a seeded RNG.

        Uses secrets.randbits for the underlying normal variate to avoid
        using Python's default random module (which is deterministic across
        process restarts from the same seed).
        """
        import random
        rng = random.Random(int.from_bytes(__import__("os").urandom(4), "big"))
        return math.exp(rng.gauss(mu, sigma))
