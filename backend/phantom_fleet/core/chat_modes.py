class ChatTierViolation(Exception):
    """Raised when a chat agent attempts to use a mode outside its allowlist."""


def validate_mode_for_platform(platform: str, mode_name: str) -> None:
    """Raise ChatTierViolation if the mode is not allowed on this platform.

    Every platform chat agent MUST call this before every LLM request. The
    check is the enforcement layer that keeps LinkedIn free of NSFW and
    Grindr free of corporate bland.
    """
    allowed = PLATFORM_ALLOWED_MODES.get(platform)
    if not allowed:
        raise ChatTierViolation(f"platform {platform!r} has no chat modes registered")
    if mode_name not in allowed:
        raise ChatTierViolation(
            f"chat mode {mode_name!r} not allowed on platform {platform!r}; "
            f"allowed: {allowed}"
        )


def reject_content(profile: ChatModeProfile, text: str) -> tuple[bool, str]:
    """Check generated text against the profile's rules.

    Returns (is_rejected, reason). Agents MUST call this on every LLM
    output before sending. Rejected messages are discarded and regenerated.
    """
    lower = text.lower()
    for phrase in profile.banned_phrases:
        if phrase in lower:
            return True, f"banned_phrase:{phrase}"
    if "#" in text and profile.tier != ChatTier.PROFESSIONAL:
        # Hashtags banned everywhere except accidental LinkedIn hashtag tolerance
        return True, "hashtag_banned"
    # LinkedIn professional tier has extra safety: no emojis
    if profile.tier == ChatTier.PROFESSIONAL:
        import re
        emoji_pattern = re.compile(r"[\U0001F600-\U0001F6FF\U0001F300-\U0001F5FF\U0001F900-\U0001F9FF]")
        if emoji_pattern.search(text):
            return True, "emoji_in_professional"
    word_count = len(text.split())
    if word_count > profile.max_reply_words:
        return True, f"word_count:{word_count}>max_{profile.max_reply_words}"
    return False, ""
