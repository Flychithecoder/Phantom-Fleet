"""
Platform-context-aware chat tier system.

Phantom Fleet's chat AI is NOT a single LLM with a single prompt. It is
11 platform-specific chat agents, each locked to a tier of content
appropriateness. The tier system enforces that the LinkedIn agent cannot
produce NSFW content, the Grindr agent cannot produce corporate bland,
and every platform's conversational voice matches its actual culture.

This is the core of "chat AI light years ahead": every conversation is
generated by an agent that was tuned for the exact platform, tier, and
context it operates in.

Tiers:
    1. PROFESSIONAL — LinkedIn B2B, corporate voice, zero innuendo
    2. CASUAL_SFW — TikTok, IG SFW, Threads, Discord SFW, Reddit SFW
    3. FLIRTY_SFW — IG DM flirty, dating app pre-CTA, BlueSky casual
    4. MIXED — X DMs, Threads private, Telegram public, Discord NSFW servers
    5. NSFW — Grindr chat, Telegram VIP private, OF/Fanvue chat

Each tier has:
    - A system prompt profile (tone, vocabulary, slang, restrictions)
    - A banned-phrase list (LLM-tell filter + explicit-rules filter)
    - An allowed content type whitelist (text only / text+emoji / text+media)
    - A CTA cadence policy (how soon is a CTA acceptable)
    - A handoff policy (when to escalate to Chat AI agents / real human)
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import IntEnum


class ChatTier(IntEnum):
    """Content appropriateness tier."""

    PROFESSIONAL = 1  # LinkedIn — suit-and-tie
    CASUAL_SFW = 2    # TikTok, IG SFW, Threads — friend voice
    FLIRTY_SFW = 3    # IG DM, dating pre-CTA — playful tease
    MIXED = 4         # X DMs, Telegram public — innuendo OK
    NSFW = 5          # Grindr, Telegram VIP, OF/Fanvue — explicit


@dataclass
class ChatModeProfile:
    """A full chat profile for one agent. Baked into each platform's chat
    agent config at creation time and immutable at runtime."""

    name: str
    tier: ChatTier
    system_prompt: str
    banned_phrases: frozenset[str]
    allowed_media: frozenset[str]  # "text" / "emoji" / "image" / "video" / "voice"
    max_reply_words: int
    max_turns_before_cta: int
    cta_allowed: bool
    typo_rate: float
    voice_msgs_allowed: bool
    handoff_mode: str  # "none" / "chat_ai" / "real_human"


