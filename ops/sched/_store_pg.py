def apply_migrations(store: str | None = None) -> None:
    dsn = store or STORE
    with psycopg.connect(dsn, autocommit=True) as c:
        with c.cursor() as cur:
            for stmt in PG_DDL:
                cur.execute(stmt)


@contextlib.contextmanager
def connect(store: str | None = None) -> Iterator[_PgConn]:
    dsn = store or STORE
    conn = psycopg.connect(dsn)
    wrapper = _PgConn(conn)
    try:
        yield wrapper
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def now_ms() -> int:
    return int(time.time() * 1000)


def transition_status(
    con: _PgConn, account_id: int, status: str, reason: str,
) -> None:
    con.execute(
        "UPDATE accounts SET status = ? WHERE id = ?",
        (status, account_id),
    )
    con.execute(
        "INSERT INTO account_status_history (account_id, status, reason, ts_ms) "
        "VALUES (?, ?, ?, ?)",
        (account_id, status, reason, now_ms()),
    )


def enqueue(
    con: _PgConn, account_id: int, kind: str,
    due_ms: int, params: dict[str, Any] | None = None,
) -> int:
    # Postgres has no lastrowid. We return the new id via RETURNING,
    # same shape the callers in ops/dispatch/wire_test.py already use.
    row = con.execute(
        "INSERT INTO action_queue (account_id, kind, due_ms, params_json, created_ms) "
        "VALUES (?, ?, ?, ?, ?) RETURNING id",
        (account_id, kind, due_ms, json.dumps(params or {}), now_ms()),
    ).fetchone()
    return int(row["id"]) if row else 0


def record_result(
    con: _PgConn, action_id: int, account_id: int,
    outcome: str, latency_ms: int | None = None,
    signal: dict[str, Any] | None = None,
) -> None:
    con.execute(
        "INSERT INTO action_results "
        "(action_id, account_id, outcome, latency_ms, signal_json, ts_ms) "
        "VALUES (?, ?, ?, ?, ?, ?)",
        (action_id, account_id, outcome, latency_ms,
         json.dumps(signal or {}), now_ms()),
    )
    new_state = "done" if outcome == "ok" else "failed"
    con.execute(
        "UPDATE action_queue SET state = ?, attempts = attempts + 1 "
        "WHERE id = ?",
        (new_state, action_id),
    )


