# ---------------------------------------------------------------------------
# DSN resolution
# ---------------------------------------------------------------------------
#
# STORE is a Postgres connection string. In SQLite-land it was a Path to
# a file; here it is the DSN. Both are "the thing you point `connect()`
# at", which is all the callers that touch `_store.STORE` care about.

def _default_dsn() -> str:
    dsn = os.environ.get("PF_PG_DSN")
    if dsn:
        return dsn
    # Compose from parts (mirrors the pattern used in CI).
    host = os.environ.get("PGHOST", "localhost")
    port = os.environ.get("PGPORT", "5432")
    user = os.environ.get("PGUSER", "postgres")
    pwd  = os.environ.get("PGPASSWORD", "postgres")
    db   = os.environ.get("PGDATABASE", "phantom_fleet")
    return f"postgresql://{user}:{pwd}@{host}:{port}/{db}"


STORE: str = _default_dsn()


