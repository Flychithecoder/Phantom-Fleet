# ---------------------------------------------------------------------------
# Connection adapter
# ---------------------------------------------------------------------------

_PLACEHOLDER_RE = re.compile(r"\?")


def _translate_sql(sql: str) -> str:
    """Rewrite '?' placeholders to '%s' for psycopg.

    Also doubles any bare '%' so psycopg's parameter parser doesn't choke
    on literals (e.g. LIKE '%foo%'). We do that before swapping '?'.
    No call site in ops/sched or ops/dispatch uses LIKE patterns, but
    the escape keeps the helper future-proof.
    """
    s = sql.replace("%", "%%")
    s = _PLACEHOLDER_RE.sub("%s", s)
    return s


class _PgCursor:
    """Thin wrapper so callers can do row['col']."""

    __slots__ = ("_cur",)

    def __init__(self, cur: Any) -> None:
        self._cur = cur

    def fetchone(self) -> Any:
        return self._cur.fetchone()

    def fetchall(self) -> list[Any]:
        return self._cur.fetchall()

    def __iter__(self) -> Iterator[Any]:
        return iter(self._cur)

    @property
    def lastrowid(self) -> int:
        # Postgres has no lastrowid; call sites use RETURNING id. We keep
        # the property so code that reads cur.lastrowid during a hot swap
        # fails loudly rather than silently returning stale ints.
        raise RuntimeError(
            "lastrowid is unavailable on the Postgres backend; use "
            "`cur = con.execute(..., RETURNING id); row = cur.fetchone()`."
        )

    def close(self) -> None:
        self._cur.close()


class _PgConn:
    """Quacks like sqlite3.Connection for the sched/dispatch call sites."""

    def __init__(self, conn: Any) -> None:
        self._c = conn

    # The row_factory attribute is set by legacy code (`con.row_factory
    # = sqlite3.Row`). We've already configured dict_row at cursor
    # creation, so just absorb writes.
    row_factory: Any = None

    def execute(self, sql: str, params: Any = ()) -> _PgCursor:
        # Explicitly route PRAGMA away: legacy modules issue
        # "PRAGMA foreign_keys = ON" after connect. FK enforcement is
        # already on in Postgres by default, so this is a no-op.
        if sql.strip().upper().startswith("PRAGMA"):
            return _PgCursor(_NullCursor())
        cur = self._c.cursor(row_factory=dict_row)
        cur.execute(_translate_sql(sql), tuple(params) if params else None)
        return _PgCursor(cur)

    def executemany(self, sql: str, seq_of_params: Any) -> None:
        cur = self._c.cursor()
        cur.executemany(_translate_sql(sql), list(seq_of_params))
        cur.close()

    def executescript(self, script: str) -> None:
        """Execute several ';'-separated statements. Mirrors
        sqlite3.Connection.executescript. We let psycopg3 parse the
        script by just handing it the whole string — psycopg accepts
        multi-statement execute when there are no params."""
        # Strip trivial comments and blank lines so a stray "--" at the
        # top of a DDL block doesn't confuse the parser. Not strictly
        # needed with psycopg3 >=3.1, but cheap.
        cur = self._c.cursor()
        cur.execute(script)
        cur.close()

    def commit(self) -> None:
        self._c.commit()

    def rollback(self) -> None:
        self._c.rollback()

    def close(self) -> None:
        self._c.close()

    # Some call sites use `con.cursor()` directly.
    def cursor(self) -> _PgCursor:
        return _PgCursor(self._c.cursor(row_factory=dict_row))


class _NullCursor:
    def fetchone(self): return None
    def fetchall(self): return []
    def __iter__(self): return iter(())
    def close(self): pass


