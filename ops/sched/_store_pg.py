def claim_lock_clause() -> str:
    """Return the SQL suffix the dispatcher appends to its claim SELECT.

    On Postgres we lock the candidate rows with FOR UPDATE SKIP LOCKED
    so two workers pulling in parallel never pick the same action.
    On SQLite (BEGIN IMMEDIATE semantics) the sibling in `_store.py`
    returns the empty string.
    """
    # `OF q` scopes the row lock to action_queue only; without it,
    # joined accounts and clone_assignments rows would be locked too
    # and worker pairs could stall each other on unrelated state.
    return " FOR UPDATE OF q SKIP LOCKED"


def is_postgres() -> bool:
    return True
