"""Postgres backend for the sched/dispatch persistence layer.

Mirrors the public surface of `ops.sched._store` so every caller
(sched/dispatch/picker/hydrator/admission/cron) keeps compiling and
running without a line change. Selection happens in `_store.py` at
import time via the ``PF_STORE`` env var; this module is a drop-in.

Design rules:
  * Same functions, same signatures. `connect()` returns an adapter
    that quacks like a `sqlite3.Connection`:
      - `execute(sql, params)` accepts '?' placeholders (we rewrite to
        psycopg's '%s'); returns a cursor you can `.fetchone()` /
        `.fetchall()` on, with rows reachable as `row["col"]`.
      - `executescript(sql)` runs several statements separated by `;`.
      - `PRAGMA ...` is a no-op (sqlite dialect leaks through some
        legacy paths — we swallow it rather than fail).
      - `commit()`, `rollback()`, `close()`.
  * All inserts that used `cur.lastrowid` now return via
    `RETURNING id` (see `enqueue`). The `con.execute(... RETURNING id)
    .fetchone()["id"]` pattern already used elsewhere in the tree
    works unchanged on both backends (SQLite 3.35+ supports it, and
    Python 3.12 bundles SQLite ≥ 3.37).
  * The `claim()` path in `ops/dispatch/_transport.py` uses
    `SELECT ... FOR UPDATE SKIP LOCKED` on Postgres. See
    `claim_lock_clause()` below and the note in `_transport.claim`.
    Claim semantics are unchanged from the caller's perspective: the
    returned rows are owned by this worker until it either records a
    result, releases, or crashes (then `sweep_stale_claims` reaps).
"""
